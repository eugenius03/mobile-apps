export const getMockSearch = (query = '', page = 1, type = '') => {
  const q = query.trim().toLowerCase();
  let filtered = MOCK_MOVIES;

  if (q) {
    filtered = filtered.filter((m) => m.Title.toLowerCase().includes(q));
  }

  if (type && type !== 'all') {
    filtered = filtered.filter((m) => m.Type.toLowerCase() === type.toLowerCase());
  }

  const pageSize = 10;
  const start = (page - 1) * pageSize;
  const end = start + pageSize;
  const paginated = filtered.slice(start, end);

  return {
    Search: paginated,
    totalResults: String(filtered.length),
    Response: paginated.length > 0 ? 'True' : 'False',
    Error: paginated.length === 0 ? 'Movie not found!' : undefined,
  };
};

